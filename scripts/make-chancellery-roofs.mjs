import fs from 'node:fs';
import clipping from 'polygon-clipping';
import { CAMPUS } from '../dist/campus-data.js';
import { chancelleryGeometry } from '../dist/upper-campus-data.js';
import { frameRectangle } from '../dist/geometry.js';
const b=CAMPUS.buildings.find(b=>b.id==='chancellery'),g=chancelleryGeometry(b),w=g.west;
const polygon=b=>[b.points,...b.holes||[]].map(r=>r.map(p=>[p.x,p.z]));
const region=[frameRectangle(g.frame,w.maxU-w.minU,w.maxV-w.minV,(w.minU+w.maxU)/2,(w.minV+w.maxV)/2).map(p=>[p.x,p.z])];
const western=clipping.intersection(polygon(b),region),other=clipping.difference(polygon(b),western),output=[];
for(const [kind,geometry]of [['vaults',western],['flat',other]])for(const rings of geometry){
  const points=r=>r.slice(0,-1).map(([x,z])=>({x,z}));
  output.push({kind,points:points(rings[0]),holes:rings.slice(1).map(points),reconstructed:true});
}
fs.writeFileSync(new URL('../dist/chancellery-roofs.js',import.meta.url),
  '// Reconstructed roof regions within the mapped Chancellery outline. Generated by scripts/make-chancellery-roofs.mjs.\nexport const CHANCELLERY_ROOFS = '+JSON.stringify(output,null,2)+';\n');
console.log(`${output.length} Chancellery roof regions`);
