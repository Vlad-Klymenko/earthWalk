import fs from 'node:fs';
import clipping from 'polygon-clipping';
import { CAMPUS } from '../dist/campus-data.js';

// Preserve OSM outlines and courtyard holes while subdividing massing inferred
// from architect / college photographs. These are NOT mapped building parts.
const u={x:.9867962476101311,z:.16196655735850177},v={x:-u.z,z:u.x};
const polygon=b=>[b.points,...(b.holes||[])].map(r=>r.map(p=>[p.x,p.z]));
const rectangle=(a,b,c,d)=>[[[a*u.x+c*v.x,a*u.z+c*v.z],[b*u.x+c*v.x,b*u.z+c*v.z],[b*u.x+d*v.x,b*u.z+d*v.z],[a*u.x+d*v.x,a*u.z+d*v.z]]];
const output=[];
function emit(parent,geometry,height,floors,minHeight=0){
  for(const rings of geometry){
    const points=ring=>ring.slice(0,-1).map(([x,z])=>({x,z}));
    output.push({id:`${parent}-reconstruction-${output.length}`,parent,height,floors,minHeight,
      heightSource:'estimated from reference photographs',reconstructed:true,
      points:points(rings[0]),holes:rings.slice(1).map(points)});
  }
}
const village=CAMPUS.buildings.find(b=>b.id==='osm-relation-2637829-0'),footprint=polygon(village);
const bands=[[-25.3,-13.5],[13.5,24.2],[48.7,61],[85.8,97.5],[132.8,142]];
const wings=clipping.union(...bands.map(([a,b])=>rectangle(a,b,-300,-170)));
const east=rectangle(145,230,-300,-170),low=clipping.difference(footprint,wings);
const masses=[{geometry:clipping.intersection(footprint,wings),height:25.6,floors:8},
  {geometry:clipping.difference(low,east),height:12.8,floors:4},
  {geometry:clipping.intersection(low,east),height:9.6,floors:3}];
// Actual public footways cross the mapped building footprint. Their corridor
// locations are retained; extra width and overhead clearance are reconstructed.
const passageIds=[297697333,280268500,280268498,280268503];
const passages=CAMPUS.paths.filter(p=>passageIds.some(id=>p.id===`osm-way-${id}`));
const passagePolygons=passages.flatMap(p=>p.points.slice(1).map((b,i)=>{
  const a=p.points[i],len=Math.hypot(b.x-a.x,b.z-a.z),dx=(b.x-a.x)/len,dz=(b.z-a.z)/len,nx=-dz*1.5,nz=dx*1.5;
  // Extend through each threshold so player radius and wall seams do not close
  // a passage whose source path ends exactly on the courtyard boundary.
  return [[[a.x-dx+nx,a.z-dz+nz],[b.x+dx+nx,b.z+dz+nz],[b.x+dx-nx,b.z+dz-nz],[a.x-dx-nx,a.z-dz-nz]]];
}));
const corridors=clipping.union(...passagePolygons);
for(const mass of masses){
  emit(village.id,clipping.difference(mass.geometry,corridors),mass.height,mass.floors);
  emit(village.id,clipping.intersection(mass.geometry,corridors),mass.height,mass.floors,mass.floors===8?5.8:3.2);
}
const ncv=CAMPUS.buildings.find(b=>b.id==='new-college-village'),ncvShape=polygon(ncv);
const ncvLow=clipping.intersection(ncvShape,rectangle(-258,-235,-20,10));
emit(ncv.id,clipping.difference(ncvShape,ncvLow),25.6,7);
emit(ncv.id,ncvLow,13.2,4);
fs.writeFileSync(new URL('../dist/residential-parts.js',import.meta.url),
  '// OSM footprint partitions with explicitly reconstructed heights. Generated by scripts/make-residential-parts.mjs.\nexport const RESIDENTIAL_PARTS = '+JSON.stringify(output,null,2)+';\n'+
  'export const VILLAGE_PASSAGES = '+JSON.stringify(passages.map(p=>({id:p.id,points:p.points,width:p.width})),null,2)+';\n');
console.log(`${output.length} reconstructed residential masses; ${passages.length} mapped through-passages`);

const raw=JSON.parse(fs.readFileSync(new URL('../dist/data/unsw.json',import.meta.url))),nodes=new Map(raw.elements.filter(e=>e.type==='node').map(e=>[e.id,e]));
const ids=[609912635,609912638,609912640];
const parts=raw.elements.filter(e=>ids.includes(e.id)).map(e=>({id:`osm-part-${e.id}`,parent:'osm-way-164558658',osmId:e.id,
  height:+e.tags.height,minHeight:+e.tags.min_height,heightSource:'mapped',
  points:e.nodes.slice(0,-1).map(id=>nodes.get(id)).map(p=>({x:+((p.lon-CAMPUS.center.lon)*Math.PI/180*6371008.8*Math.cos(CAMPUS.center.lat*Math.PI/180)).toFixed(3),z:+((CAMPUS.center.lat-p.lat)*Math.PI/180*6371008.8).toFixed(3)}))}));
fs.writeFileSync(new URL('../dist/nida-parts.js',import.meta.url),
  '// Actual OSM building-part outlines, height and min_height tags, retained in dist/data/unsw.json.\nexport const NIDA_PARTS = '+JSON.stringify(parts,null,2)+';\n');
console.log(`${parts.length} mapped NIDA upper building parts`);
