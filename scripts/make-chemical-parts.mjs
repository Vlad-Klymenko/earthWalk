import fs from 'node:fs';
import clipping from 'polygon-clipping';
import { CAMPUS } from '../dist/campus-data.js';
import { orientedFrame, framePoint } from '../dist/geometry.js';

const b=CAMPUS.buildings.find(b=>b.id==='chemical-sciences'),f=orientedFrame(b.points);
const local=p=>({u:(p.x-f.x)*f.u.x+(p.z-f.z)*f.u.z,v:(p.x-f.x)*f.v.x+(p.z-f.z)*f.v.z});
// The tower is the long central-west bar, behind the southern teaching wing.
// Public 2016 massing drawings and Street View distinguish it from the lower
// northeast service block. Split lines follow existing perimeter returns;
// internal boundaries remain reconstructed, not surveyed building parts.
const u0=local(b.points[13]).u,u1=local(b.points[18]).u,v0=-f.length/2-.001,v1=local(b.points[6]).v;
const boundary=[[[u0,v0],[u1,v0],[u1,v1],[u0,v1]].map(([u,v])=>{const p=framePoint(f,u,v);return[p.x,p.z];})];
const footprint=[b.points,...b.holes].map(r=>r.map(p=>[p.x,p.z]));
const tower=clipping.intersection(footprint,boundary),podium=clipping.difference(footprint,tower);
const parts=[];
for(const [role,geometry,height,roof]of [['tower',tower,b.height,b.height],['podium',podium,15,15]])for(const rings of geometry){
  const points=ring=>ring.slice(0,-1).map(([x,z])=>({x,z}));
  parts.push({id:`f10-${role}-${parts.length}`,parent:b.id,role,reconstructed:true,height,roof,
    heightSource:role==='tower'?'retained parent overall map tag':'photograph-led estimate',
    boundarySource:'reconstructed split at mapped outline returns',
    points:points(rings[0]),holes:rings.slice(1).map(points)});
}
fs.writeFileSync(new URL('../dist/chemical-parts.js',import.meta.url),
  '// Reconstructed F10 massing within the retained OSM outline. Generated by scripts/make-chemical-parts.mjs.\n'+
  '// Retains parent 45 m tag for comparison. Rendering uses the approximate reported parapet RL; lower-wing height and internal boundaries are estimates.\n'+
  'export const CHEMICAL_PARTS = '+JSON.stringify(parts,null,2)+';\n');
console.log(`${parts.length} reconstructed Chemical Sciences parts`);
